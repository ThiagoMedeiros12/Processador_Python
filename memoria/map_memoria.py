
# RAM
RAM_INICIO = 0x00000
RAM_FIM = 0x7FFFF
TAMANHO_RAM = RAM_FIM - RAM_INICIO + 1

# VRAM
VRAM_INICIO = 0x80000
VRAM_FIM = 0x8FFFF
TAMANHO_VRAM = VRAM_FIM - VRAM_INICIO + 1

# Memoria reservada
RESERVADO_INICIO = 0x90000
RESERVADO_FIM = 0x9FBFF

# I/O
IO_INICIO = 0x9FC00
IO_FIM = 0x9FFFF
TAMANHO_IO = IO_FIM - IO_INICIO + 1
